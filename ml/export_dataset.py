"""Export TAVIX-approved training examples from PostgreSQL into MLX chat-format JSONL.
Only builds that an engineer marked `reviewed` AND that were NOT generated by the Claude API are exported
(Anthropic's terms do not allow using Claude outputs to train other models). Use your own team's work, or outputs from your local model after you correct them."""
import json, os, random, sys
import psycopg2

url = os.getenv("DATABASE_URL", "postgresql://tavix:tavix@localhost:5432/tavix").replace("+psycopg2", "")
SYS_SPEC = "You are Tavix AI, a senior solutions architect. Return ONLY JSON."
SYS_SITE = ("You are Tavix AI, a front-end engineer. Return ONLY one complete self-contained HTML document. "
            "Create a distinctive visual theme for the client's domain and requested style; do not reuse generic TAVIX branding unless requested.")
rows = []
with psycopg2.connect(url) as c, c.cursor() as cur:
    cur.execute("SELECT sector,title,problem,spec,site_html,domain,theme FROM bookings WHERE reviewed AND build_provider <> 'anthropic' AND spec <> ''")
    for sector, title, problem, spec, html, domain, theme in cur.fetchall():
        brief = (f"Title: {title}\nSector: {sector}\nClient request: {problem}\n"
                 f"Website/product domain: {domain or 'infer from the request'}\n"
                 f"Requested visual theme: {theme or 'infer a distinctive theme from the product domain and audience'}")
        rows.append({"messages": [{"role": "system", "content": SYS_SPEC}, {"role": "user", "content": brief}, {"role": "assistant", "content": spec}]})
        if html:
            rows.append({"messages": [{"role": "system", "content": SYS_SITE}, {"role": "user", "content": brief + "\n\nSpec:\n" + spec}, {"role": "assistant", "content": html}]})
if len(rows) < 20:
    sys.exit(f"Only {len(rows)} examples. You need at least 200 good ones; 1000+ is better. Keep collecting reviewed builds.")
random.shuffle(rows); n = max(1, len(rows) // 10); os.makedirs("data", exist_ok=True)
for name, part in (("valid", rows[:n]), ("train", rows[n:])):
    with open(f"data/{name}.jsonl", "w") as f:
        f.writelines(json.dumps(r) + "\n" for r in part)
print(f"train={len(rows) - n} valid={n} -> ml/data/")
